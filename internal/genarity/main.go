// Command genarity generates fixed-arity declarations used by the framework.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
	"text/template"
)

const generatedHeader = "// Code generated by internal/genarity; DO NOT EDIT.\n\n"

type arity struct {
	Count              int
	Inputs             []int
	HasSelector        bool
	InputTypeParams    string
	InputTypeArgs      string
	OutputTypeParams   string
	OutputReceiver     string
	OutputPhantom      string
	ExplicitTypeParams string
	ClosureTypeParams  string
}

type outputTarget struct {
	path     string
	template *template.Template
}

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(args []string) error {
	flags := flag.NewFlagSet("genarity", flag.ContinueOnError)
	flags.SetOutput(os.Stderr)
	outDir := flags.String("out", ".", "directory for generated files")
	targetName := flags.String("target", "node", "ordered output target set")
	if err := flags.Parse(args); err != nil {
		return err
	}

	var targets []outputTarget
	switch *targetName {
	case "node":
		var err error
		targets, err = nodeTargets()
		if err != nil {
			return err
		}
	case "graph":
		var err error
		targets, err = graphTargets()
		if err != nil {
			return err
		}
	default:
		return fmt.Errorf("unknown target set %q", *targetName)
	}

	return generateTargets(*outDir, targets)
}

func generateTargets(outDir string, targets []outputTarget) error {
	if outDir == "" {
		return errors.New("output directory is required")
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return fmt.Errorf("creating output directory: %w", err)
	}

	data := arityModel()
	for _, target := range targets {
		source, err := render(target, data)
		if err != nil {
			return err
		}
		outputPath := filepath.Join(outDir, target.path)
		if err := os.WriteFile(outputPath, source, 0o644); err != nil {
			return fmt.Errorf("writing %q: %w", outputPath, err)
		}
	}

	return nil
}

func render(target outputTarget, data []arity) ([]byte, error) {
	var output bytes.Buffer
	output.WriteString(generatedHeader)
	if err := target.template.Execute(&output, data); err != nil {
		return nil, fmt.Errorf("rendering %q: %w", target.path, err)
	}

	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting %q: %w", target.path, err)
	}
	return formatted, nil
}

func nodeManifest() []string {
	return []string{
		"outputs_gen.go",
		"nodes_gen.go",
		"closures_gen.go",
	}
}

func graphManifest() []string {
	return []string{
		"ports_gen.go",
		"registration_gen.go",
	}
}

func nodeTargets() ([]outputTarget, error) {
	templateSources := []string{
		outputsTemplate,
		nodesTemplate,
		closuresTemplate,
	}
	manifest := nodeManifest()
	targets := make([]outputTarget, 0, len(manifest))
	for index, path := range manifest {
		parsed, err := template.New(path).Parse(templateSources[index])
		if err != nil {
			return nil, fmt.Errorf("parsing %q: %w", path, err)
		}
		targets = append(targets, outputTarget{
			path:     path,
			template: parsed,
		})
	}
	return targets, nil
}

func graphTargets() ([]outputTarget, error) {
	templateSources := []string{
		portsTemplate,
		registrationTemplate,
	}
	manifest := graphManifest()
	targets := make([]outputTarget, 0, len(manifest))
	for index, path := range manifest {
		parsed, err := template.New(path).Parse(templateSources[index])
		if err != nil {
			return nil, fmt.Errorf("parsing %q: %w", path, err)
		}
		targets = append(targets, outputTarget{
			path:     path,
			template: parsed,
		})
	}
	return targets, nil
}

func arityModel() []arity {
	model := make([]arity, 0, 9)
	for count := range 9 {
		inputs := make([]int, count)
		for index := range inputs {
			inputs[index] = index + 1
		}
		model = append(model, arity{
			Count:              count,
			Inputs:             inputs,
			HasSelector:        count >= 2,
			InputTypeParams:    typeParameters("I", count),
			InputTypeArgs:      typeArguments("I", count),
			OutputTypeParams:   typeParameters("O", count),
			OutputReceiver:     typeArguments("O", count),
			OutputPhantom:      phantomTypes("O", count),
			ExplicitTypeParams: handlerTypeParameters(true, count),
			ClosureTypeParams:  handlerTypeParameters(false, count),
		})
	}
	return model
}

func typeParameters(prefix string, count int) string {
	if count == 0 {
		return ""
	}
	return "[" + joinedNames(prefix, count) + " any]"
}

func typeArguments(prefix string, count int) string {
	if count == 0 {
		return ""
	}
	return "[" + joinedNames(prefix, count) + "]"
}

func phantomTypes(prefix string, count int) string {
	if count == 0 {
		return ""
	}
	return "[0]func(" + joinedNames(prefix, count) + ")"
}

func handlerTypeParameters(explicitState bool, inputCount int) string {
	parts := make([]string, 0, inputCount+3)
	if explicitState {
		parts = append(parts, "S")
	}
	for index := 1; index <= inputCount; index++ {
		parts = append(parts, fmt.Sprintf("I%d", index))
	}

	var declaration strings.Builder
	declaration.WriteByte('[')
	if len(parts) > 0 {
		declaration.WriteString(strings.Join(parts, ", "))
		declaration.WriteString(" any, ")
	}
	declaration.WriteString("O OutputSet, E any]")
	return declaration.String()
}

func joinedNames(prefix string, count int) string {
	names := make([]string, count)
	for index := range names {
		names[index] = fmt.Sprintf("%s%d", prefix, index+1)
	}
	return strings.Join(names, ", ")
}

